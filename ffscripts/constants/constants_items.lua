function FiendFolio.GetRandomSoulstone(rng, ignoreSoulOfRandom)
	local validSouls = {}
	for _, soul in ipairs(FiendFolio.Soulstones) do
		if soul[2]() and (not ignoreSoulOfRandom or soul[1] ~= FiendFolio.ITEM.CARD.SOUL_OF_RANDOM) then
			table.insert(validSouls, soul[1])
		end
	end
	if #validSouls == 0 then
		validSouls = {Card.RUNE_SHARD}
	end
	return validSouls[rng:RandomInt(#validSouls) + 1]
end

