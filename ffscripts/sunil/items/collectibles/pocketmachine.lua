local function chooseIndex(rng, tab)
	local failsafe = 0
	local choice
	while failsafe < 100 do
		local candidate = mod:RandomIndex(tab, rng)
		if mod.IsItemUnlocked(candidate.Id) then
			choice = candidate
			break
		end
		failsafe = failsafe + 1
	end

	return choice or tab[1]
end

