local function shootLaser(familiar, data, direction, laservar, firevel, mult, isBabyBender, isSuperpositioned)
	local laser = EntityLaser.ShootAngle(laservar, familiar.Position, firevel:GetAngleDegrees(), 3, Vector(0, -20), familiar)
	laser.Parent = familiar
	laser.CollisionDamage = 3.5 * mult
	laser.Color = data.hakkerocolor

	if laservar == LaserVariant.LIGHT_BEAM then
		laser.Timeout = 20
		laser:SetScale(0.75)
		familiar.Child = laser
		if direction == Direction.LEFT then
			laser.PositionOffset = Vector(-12,-26)
			laser.DepthOffset = 1
		elseif direction == Direction.RIGHT then
			laser.PositionOffset = Vector(12,-26)
			laser.DepthOffset = 1
		elseif direction == Direction.UP then
			laser.PositionOffset = Vector(0,-35)
			laser.DepthOffset = -1
		elseif direction == Direction.DOWN then
			laser.PositionOffset = Vector(0,-19)
			laser.DepthOffset = 1
		end
	else
		laser.DisableFollowParent = true
	end
	
	if isBabyBender then
		laser:AddTearFlags(TearFlags.TEAR_HOMING)
		laser.Color = Color(1,1,1,1,0,0,0,3,1,3.5,1)
		if isSuperpositioned then
			local laserCol = laser.Color
			laserCol.A = laserCol.A / 4
			laser.Color = laserCol
		end
	else
		mod:GetEntityData(laser).minihakkerocolours = true
		mod:GetEntityData(laser).minihakkerorainbow = laservar == LaserVariant.LIGHT_BEAM
	end
	
	if isSuperpositioned then
		mod:GetEntityData(laser).minihakkerosuperpositioned = true
	end
	
	laser:Update()
end

mod:AddCallback(ModCallbacks.MC_FAMILIAR_UPDATE, function(_, familiar)
	local player = familiar.Player
	local data = mod:GetEntityData(familiar)
	local sprite = familiar:GetSprite()
	local layers = sprite:GetAllLayers()
	local isSuperpositioned = mod:isSuperpositionedPlayer(familiar.Player)
	local isSirenCharmed = mod:isSirenCharmed(familiar)
	local isKingBabyTarget = mod:isKingBabyAParent(familiar, true)
	local isPlayerMarked = familiar.Player:HasCollectible(CollectibleType.COLLECTIBLE_MARKED)

	if not data.state then
		familiar:AddToOrbit(0)
		familiar.FireCooldown = 0
		data.state = "Float"
		data.stateframe = 0
		data.attemptssincelastmasterspark = 0
	else
		if not familiar.Child then
			familiar.FireCooldown = familiar.FireCooldown - ((player and player:HasTrinket(TrinketType.TRINKET_FORGOTTEN_LULLABY) and 2) or 1)
			familiar.FireCooldown = math.max(0, familiar.FireCooldown)
		end
		
		data.stateframe = data.stateframe + 1
	end
	
	local direction = player:GetFireDirection()
	data.lastdirection = (data.lastdirection ~= nil and data.lastdirection) or direction
	data.lastdirection = (direction ~= Direction.NO_DIRECTION and direction) or data.lastdirection
	if familiar.FireCooldown == 0 and mod.IsPlayerTryingToShoot(player) and data.hakkerocolor then
		data.stateframe = 0
		familiar.FireCooldown = 22
		if data.masterspark then
			data.state = "Masterspark"
			familiar.FireCooldown = 36
		end
		if Sewn_API then
			if Sewn_API:IsUltra(data) then
				familiar.FireCooldown = familiar.FireCooldown - 8
			elseif Sewn_API:IsSuper(data) then
				familiar.FireCooldown = familiar.FireCooldown - 4
			end
		end
		
		local firevel = mod.GetFamiliarShootingDirection(familiar):Resized(10)
		local mult = familiar:GetMultiplier()
		local isBabyBender = player:HasTrinket(TrinketType.TRINKET_BABY_BENDER)
		
		local laservar = LaserVariant.THIN_RED
		if data.masterspark then
			laservar = LaserVariant.LIGHT_BEAM
			data.masterspark = nil
			data.attemptssincelastmasterspark = 0
			familiar.Color = Color(1,1,1,1,0,0,0)
			
			mod.scheduleForUpdate(function()
				shootLaser(familiar, data, direction, laservar, firevel, mult, isBabyBender, isSuperpositioned)
			end, 6)
		else
			shootLaser(familiar, data, direction, laservar, firevel, mult, isBabyBender, isSuperpositioned)
		end
	end
	
	if data.state == "Float" then
		if not sprite:IsPlaying("Idle") then
			local frame = sprite:GetFrame()
			sprite:Play("Idle", true)
			sprite:SetFrame(frame)
			sprite.FlipX = false
		end
		if sprite:IsEventTriggered("color1") and data.hakkerocolor then
			layers[3]:SetColor(data.hakkerocolor)
		end
		if sprite:IsEventTriggered("color2") then
			data.hakkerocount = data.hakkerocount or 1
			data.hakkerocolor = miniHakkeroLaserColours[data.hakkerocount]
			data.hakkerocount = data.hakkerocount+2
			if data.hakkerocount > #miniHakkeroLaserColours then
				data.hakkerocount = 1
			end
			layers[2]:SetColor(data.hakkerocolor)
		end
	elseif data.state == "Masterspark" then
		if sprite:IsPlaying("Idle") then
			familiar:SetColor(Color(1,1,1,1,1,1,1),5,1,true,true)
			sprite:Play("ToShoot", true)
		end
		if data.lastdirection == Direction.LEFT then
			if sprite:IsFinished("ToShoot") then
				sprite:Play("ShootSide", true)
				sprite.FlipX = true
				data.state = "Shooting"
				data.stateframe = 0
			end
		elseif data.lastdirection == Direction.RIGHT then
			if sprite:IsFinished("ToShoot") then
				sprite:Play("ShootSide", true)
				data.state = "Shooting"
				data.stateframe = 0
			end
		elseif data.lastdirection == Direction.UP then
			if sprite:IsFinished("ToShoot") then
				sprite:Play("ShootUp", true)
				data.state = "Shooting"
				data.stateframe = 0
			end
		elseif data.lastdirection == Direction.DOWN then
			if sprite:IsFinished("ToShoot") then
				sprite:Play("ShootDown", true)
				data.state = "Shooting"
				data.stateframe = 0
			end
		end
	elseif data.state == "Shooting" then
		if data.stateframe > 24 then
			if sprite:IsPlaying("ShootSide") then
				sprite:Play("ShootSideToIdle", true)
			elseif sprite:IsPlaying("ShootUp") then
				sprite:Play("ShootUpToIdle", true)
			elseif sprite:IsPlaying("ShootDown") then
				sprite:Play("ShootDownToIdle", true)
			end
			if sprite:IsFinished("ShootSideToIdle") or 
			sprite:IsFinished("ShootUpToIdle") or 
			sprite:IsFinished("ShootDownToIdle") then
				data.state = "Float"
				data.stateframe = 0
			end
		end
	end
	
	if familiar.Player then
		familiar.Velocity = (familiar:GetOrbitPosition(Vector(0,0)) + familiar.Player.Position) - familiar.Position
	else
		familiar.Velocity = Vector(0,0)
	end
	
	if data.masterspark and not isSirenCharmed then
		local flash = 0.2*math.abs(math.sin((data.sparkreadyflash or 0) * math.pi / 12))
		familiar.Color = Color(1,1,1,1,flash,flash,flash)
		data.sparkreadyflash = (data.sparkreadyflash or 0) + 1
	end
end, mod.ITEM.FAMILIAR.REPRESSION)

mod:AddCallback(ModCallbacks.MC_PRE_FAMILIAR_COLLISION, function(_, familiar, collider)
	local isSirenCharmed = mod:isSirenCharmed(familiar)
	
	if collider.Type == 9 and not isSirenCharmed then
        local proj = collider:ToProjectile()
		if proj:HasProjectileFlags(ProjectileFlags.CANT_HIT_PLAYER) then
			return true
		end
		proj:Die()
		
		local data = mod:GetEntityData(familiar)
		if math.random() <= 1 / math.max(1, maxBulletsBeforeMasterSpark - (data.attemptssincelastmasterspark or 0)) then
			data.masterspark = true
		end
		data.attemptssincelastmasterspark = (data.attemptssincelastmasterspark or 0) + 1
    end
end, mod.ITEM.FAMILIAR.REPRESSION)

mod:AddCallback(ModCallbacks.MC_PRE_LASER_UPDATE, function(_, laser)
	local data = mod:GetEntityData(laser)
	if data.minihakkerocolours then
		if data.minihakkerorainbow then
			laser.Color = miniHakkeroLaserColours[game:GetFrameCount() % #miniHakkeroLaserColours + 1]
			if data.minihakkerosuperpositioned then
				laser.Color = Color.Lerp(laser.Color, laser.Color, 1)
				laser.Color.A = laser.Color.A / 4
			end
		elseif laser.FrameCount == 0 then
			if data.hakkerocolor then
				laser.Color = data.hakkerocolor
			end
			if data.minihakkerosuperpositioned then
				laser.Color.A = laser.Color.A / 4
			end
		end
	end
end)