function FiendFolio:rerollActiveItemMStyle(player, slot, oldItem)
	if slot >= 0 and slot < 3 then
		local itemConfig = Isaac.GetItemConfig()
		local ActiveChoices = {}
		for i=1, itemConfig:GetCollectibles().Size-1 do
			local item = itemConfig:GetCollectible(i)
			if item then
				if item.Type == ItemType.ITEM_ACTIVE
				and item:IsAvailable()
				and item.ID ~= oldItem
				then
					table.insert(ActiveChoices, item)
				end
			end
		end
		local item = ActiveChoices[math.random(#ActiveChoices)].ID
		player:RemoveCollectible(oldItem, true, slot, true)
		if slot == ActiveSlot.SLOT_POCKET then
			player:SetPocketActiveItem(item, ActiveSlot.SLOT_POCKET)
		else
			player:AddCollectible(item, 0, false, slot)
		end
	end
end

