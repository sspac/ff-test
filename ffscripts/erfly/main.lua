function mod:heldItemsPlayerUpdate(player, data)
	--Holding stuff up
	if data.holdingFFItem then
		if player:IsExtraAnimationFinished() and not (data.holdingFFItem == mod.ITEM.COLLECTIBLE.SANGUINE_HOOK and Isaac.GetChallenge() == mod.challenges.isaacRebuilt) then
			data.holdingFFItem = nil
			data.holdingFFItemSlot = nil
		end
		local aim
		if aimBlacklist[data.holdingFFItem] then
			aim = mod.GetCorrectedFiringInput(player, true)
		else
			aim = mod.GetCorrectedFiringInput(player)
		end
		if data.holdingFFItem == FiendFolio.ITEM.COLLECTIBLE.KALUS_HEAD then
			mod:useHeldKaluHead(player, data, aim)
		else
			if aim:Length() > 0.5 then
				aim = aim:Normalized()
				if data.holdingFFItemSlot and data.holdingFFItemSlot == "card" then
					if data.holdingFFItem == FiendFolio.ITEM.CARD.DARK_HOLE then
						mod:useHeldDarkHole(player, data, aim)
					elseif data.holdingFFItem == FiendFolio.ITEM.CARD.TRAINER_CARD then
						mod:useHeldTrainerCard(player, data, aim)
					end
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.SANGUINE_HOOK then
					mod:useHeldSanguineHook(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.GRAPPLING_HOOK then
					mod:useHeldGrapplingHook(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.TOY_CAMERA then
					mod:useHeldItemToyCamera(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.LEMON_MISHUH then
					mod:throwLemonMishuh(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.D2 then
					mod:throwD2(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.GAPER_IN_A_JAR then
					mod:useGaperInAJar(player, aim, data.holdingFFItemSlot)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.GREEN_CANDLE then
					mod:useHeldGreenCandle(player, data, aim)
				elseif data.holdingFFItem == mod.ITEM.COLLECTIBLE.HOT_SHOT then
					mod:useFireballActive(player, aim, data.holdingFFItemSlot)
				end
				if data.holdingFFItem and (not data.firingSanguineHookShot) then
					if data.HoldingFFItemBlankVisual then
						if REPENTANCE_PLUS then
							player:AnimatePickup(Sprite(), false, "HideItem")
						else
							--Keeping this here to be safe since I know it worked well enough before
							player:AnimateCollectible(-1, "HideItem", "PlayerPickup")
						end
						data.HoldingFFItemBlankVisual = nil
					else
						player:AnimateCollectible(data.holdingFFItem, "HideItem", "PlayerPickup")
					end
				else
					data.firingSanguineHookShot = nil
				end
				data.holdingFFItem = nil
				data.holdingFFItemSlot = nil
				data.HoldingFFItemBlankVisual = nil
			end
		end
	else
		data.holdingFFItemSlot = nil
	end
end
