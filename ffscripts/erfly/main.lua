local pickingupitem = {}
function mod:itemPickupStuff(player,data)
	if not player:IsItemQueueEmpty() then
		if not pickingupitem[player.InitSeed] then
			pickingupitem[player.InitSeed] = true
			local queueItemData = player.QueuedItem
			if queueItemData.Item then
				if queueItemData.Item:IsTrinket() then
					mod:veilTrinketQueueCheck(player, queueItemData.Item)
					if queueItemData.Item.ID == mod.ITEM.TRINKET.NOTABLE_ALBUM then
						if not data.FFPlayedTrinketSound then
							sfx:Play(mod.Sounds.BuddyHolly, 1, 0, false, 1)
							data.FFPlayedTrinketSound = true
						end
					end
				else
					if queueItemData.Item.ID == mod.ITEM.COLLECTIBLE.GRABBER then
						if mod:cancelCollectiblePickupSound() then
							sfx:Play(mod.Sounds.ClapPickup, 1, 0, false, 1)
						end
					elseif player.QueuedItem.Item.ID == FiendFolio.ITEM.COLLECTIBLE.HUNDRED_PERCENT_ORANGE_JUICE then
						if mod:cancelCollectiblePickupSound() then
							if math.random(10) == 1 then
								FiendFolio:trySayAnnouncerLine(mod.Sounds.OrangeJuiceA100Percent, 0, 30)
							end
							sfx:Play(mod.Sounds.OrangeJuiceChapterStart, 0.5, 2, false, 1)
						end
					elseif queueItemData.Item.ID == mod.ITEM.COLLECTIBLE.THE_LAST_BLACK_HEART then
						if mod:cancelCollectiblePickupSound() then
							sfx:Play(SoundEffect.SOUND_UNHOLY, 1, 2, false, 1)
						end
					elseif queueItemData.Item.ID == mod.ITEM.COLLECTIBLE.MYSTERIOUS_FEDORA then
						if mod:cancelCollectiblePickupSound() then
							sfx:Play(mod.Sounds.MysteriousStrangerAppears, 1, 2, false, 1)
						end
					elseif queueItemData.Item.ID == mod.ITEM.COLLECTIBLE.BAD_DATA then
						mod:GetEntityData(player).PickingUpBAD_DATA = 0
					elseif queueItemData.Item.ID == mod.ITEM.COLLECTIBLE.COOL_SKULL_INSIGNIA then
						if mod:cancelCollectiblePickupSound() then
							sfx:Play(mod.Sounds.BadToTheBone, 0.75)
						end
					end
				end
			end
		end
	else
		pickingupitem[player.InitSeed] = false
	end
end

