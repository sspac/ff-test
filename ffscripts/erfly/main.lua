	[FiendFolio.ITEM.COLLECTIBLE.KALUS_HEAD] 		= true,
	[FiendFolio.ITEM.COLLECTIBLE.AIMED_SHOT]		= true,
	[FiendFolio.ITEM.COLLECTIBLE.HOT_SHOT]			= true,
